// Sayt tillari. O'zbekcha manzillar qo'shimchasiz (/chorsu/turk-tili),
// ruscha va inglizcha — /ru/... va /en/... ko'rinishida.
export const locales = ["uz", "ru", "en"];
export const defaultLocale = "uz";

export const localeLabels = { uz: "UZ", ru: "RU", en: "EN" };
export const ogLocales = { uz: "uz_UZ", ru: "ru_RU", en: "en_US" };

export function isLocale(value) {
  return locales.includes(value);
}

// "/chorsu/turk-tili" -> "/ru/chorsu/turk-tili" (o'zbekcha uchun o'zgarmaydi)
export function localePath(lang, path = "/") {
  if (lang === defaultLocale) return path;
  return path === "/" ? `/${lang}` : `/${lang}${path}`;
}

// Har bir til uchun canonical va hreflang havolalari.
export function alternatesFor(lang, path) {
  return {
    canonical: localePath(lang, path),
    languages: {
      ...Object.fromEntries(locales.map((code) => [code, localePath(code, path)])),
      "x-default": localePath(defaultLocale, path),
    },
  };
}

